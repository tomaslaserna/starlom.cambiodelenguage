CREATE TABLE IF NOT EXISTS public.order_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id bigint NOT NULL,
  quote_id uuid NOT NULL REFERENCES public.quotes(id) ON DELETE RESTRICT,
  channel text NOT NULL CHECK (channel IN ('tienda', 'desafio', 'portal')),
  status text NOT NULL DEFAULT 'solicitud' CHECK (status IN ('solicitud', 'aprobada', 'rechazada', 'cancelada')),
  payment_method text NOT NULL DEFAULT 'cuenta_corriente',
  payment_status text NOT NULL DEFAULT 'pendiente' CHECK (payment_status IN ('pendiente', 'pagado', 'rechazado')),
  payment_reference text,
  approved_order_id uuid REFERENCES public.sales(id) ON DELETE SET NULL,
  approved_by uuid,
  approved_at timestamptz,
  rejected_by uuid,
  rejected_at timestamptz,
  rejection_reason text,
  sla_due_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT order_requests_company_quote_unique UNIQUE (empresa_id, quote_id)
);

CREATE INDEX IF NOT EXISTS order_requests_company_status_created_idx
  ON public.order_requests (empresa_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS order_requests_company_channel_created_idx
  ON public.order_requests (empresa_id, channel, created_at DESC);

ALTER TABLE public.order_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.order_requests FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.order_requests TO starlim_app;
CREATE POLICY order_requests_runtime ON public.order_requests
  FOR ALL TO starlim_app USING (true) WITH CHECK (true);

CREATE TABLE IF NOT EXISTS public.storefront_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id bigint NOT NULL,
  session_id uuid NOT NULL,
  event_type text NOT NULL CHECK (event_type IN (
    'page_view', 'catalog_open', 'checkout_started', 'challenge_started',
    'request_submitted', 'request_approved', 'request_rejected'
  )),
  channel text NOT NULL DEFAULT 'tienda' CHECK (channel IN ('tienda', 'desafio', 'portal')),
  request_id uuid REFERENCES public.order_requests(id) ON DELETE SET NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS storefront_events_company_created_idx
  ON public.storefront_events (empresa_id, created_at DESC);
CREATE INDEX IF NOT EXISTS storefront_events_company_session_idx
  ON public.storefront_events (empresa_id, session_id, created_at DESC);

ALTER TABLE public.storefront_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.storefront_events FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.storefront_events TO starlim_app;
CREATE POLICY storefront_events_runtime ON public.storefront_events
  FOR ALL TO starlim_app USING (true) WITH CHECK (true);

INSERT INTO public.order_requests (empresa_id, quote_id, channel, payment_method, payment_status, created_at, updated_at)
SELECT q.empresa_id, q.id,
       CASE WHEN q.source_sheet ILIKE '%desaf%' THEN 'desafio'
            WHEN q.source_sheet ILIKE '%portal%' THEN 'portal'
            ELSE 'tienda' END,
       CASE WHEN q.source_sheet ILIKE '%portal%' THEN 'cuenta_corriente' ELSE 'efectivo' END,
       'pendiente', q.created_at, now()
  FROM public.quotes q
 WHERE q.status = 'pendiente'
   AND q.converted_order_id IS NULL
   AND (q.source_sheet ILIKE '%tienda%' OR q.source_sheet ILIKE '%desaf%' OR q.source_sheet ILIKE '%portal%')
ON CONFLICT (empresa_id, quote_id) DO NOTHING;
